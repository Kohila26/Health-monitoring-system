const mongoose = require('mongoose');

const healthReportSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true
    },
    title: {
      type: String,
      default: 'Comprehensive Health Monitoring Summary'
    },
    dateRange: {
      startDate: { type: Date, required: true },
      endDate: { type: Date, required: true }
    },
    includedSections: {
      measurements: { type: Boolean, default: true },
      vitalsSummary: { type: Boolean, default: true },
      symptoms: { type: Boolean, default: true },
      medications: { type: Boolean, default: true },
      appointments: { type: Boolean, default: true },
      aiSummary: { type: Boolean, default: true }
    },
    summaryStats: {
      totalMeasurements: { type: Number, default: 0 },
      criticalAlertsCount: { type: Number, default: 0 },
      averageHeartRate: { type: Number },
      averageBP: { type: String },
      averageGlucose: { type: Number }
    },
    aiSummary: {
      text: { type: String, default: '' },
      modelUsed: { type: String, default: 'gpt-4o-mini' },
      generatedAt: { type: Date },
      disclaimer: {
        type: String,
        default: 'This summary is generated by an automated AI tool for informational purposes only. It does not constitute medical diagnosis or advice. Always consult a qualified physician.'
      }
    },
    doctorNotes: {
      type: String,
      default: ''
    },
    pdfUrl: {
      type: String
    },
    status: {
      type: String,
      enum: ['draft', 'generated', 'reviewed'],
      default: 'generated'
    }
  },
  {
    timestamps: true
  }
);

healthReportSchema.index({ user: 1, createdAt: -1 });

module.exports = mongoose.model('HealthReport', healthReportSchema);
