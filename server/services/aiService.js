const OpenAI = require('openai');

class AIService {
  constructor() {
    this.apiKey = process.env.OPENAI_API_KEY;
    this.model = process.env.OPENAI_MODEL || 'gpt-4o-mini';

    if (this.apiKey && this.apiKey !== 'your_api_key_here') {
      try {
        this.client = new OpenAI({ apiKey: this.apiKey });
      } catch (err) {
        console.warn('[AI Service] OpenAI client init notice:', err.message);
      }
    }
  }

  /**
   * System Prompt enforcing clinical boundaries and safety rules
   */
  getSystemPrompt() {
    return `
You are the AI Health Assistant for a clinical Health Monitoring System.
Your primary role is to help users organize, understand, and reflect on their recorded health metrics in simple, clear, and reassuring language.

CRITICAL MEDICAL SAFETY RULES:
1. You are an informational assistant, NOT a doctor. You NEVER diagnose medical conditions or claim to replace a physician.
2. Clearly distinguish between actual user-recorded facts and general health educational concepts.
3. NEVER invent or hallucinate measurements, prescriptions, or symptoms.
4. Avoid stating that normal readings rule out medical issues.
5. Emphasize uncertainty and data limitations whenever measurements are sparse.
6. Provide thoughtful questions the patient can bring to their next doctor visit.
7. If critical values or emergency symptoms (e.g. chest pressure, sudden numbness, severe breathing difficulty) are mentioned, instruct them to seek emergency medical care immediately.
8. Clearly conclude that this summary is AI-generated for informational monitoring purposes only.
    `.trim();
  }

  /**
   * Explain a specific measurement in simple language
   */
  async explainMeasurement({ vitalType, value, valueDetails, unit }) {
    const prompt = `
A user recorded a ${vitalType} measurement:
- Recorded Value: ${value !== undefined ? value : ''} ${valueDetails ? JSON.stringify(valueDetails) : ''} ${unit}

Please provide:
1. What this vital measurement means in simple physiological terms.
2. What the typical standard healthy adult range is.
3. 2-3 practical, general lifestyle considerations (hydration, rest, nutrition).
4. 2 relevant questions the user can ask their doctor during their next routine check-up.
Keep it structured, polite, and reassuring.
    `;

    return await this._callLLMOrFallback(prompt, {
      fallbackType: 'explain_measurement',
      vitalType,
      value: value || (valueDetails ? `${valueDetails.systolic}/${valueDetails.diastolic}` : 'N/A'),
      unit
    });
  }

  /**
   * Generate an overall health summary from vitals and symptoms
   */
  async generateHealthSummary({ vitalsSummary, recentAlerts, symptoms, medications, dateRange }) {
    const prompt = `
Please generate a structured, empathetic health summary for a patient covering ${dateRange || 'the past 30 days'}:

Vitals History Summary:
${JSON.stringify(vitalsSummary, null, 2)}

Active Symptoms:
${JSON.stringify(symptoms, null, 2)}

Active Medications:
${JSON.stringify(medications, null, 2)}

Recent Clinical Alerts:
${JSON.stringify(recentAlerts, null, 2)}

Structure your response with:
1. Executive Health Overview (factual summary of what was tracked)
2. Vital Trends & Patterns Observed (noting stability or fluctuations)
3. Medication & Symptom Observations
4. Suggested Discussion Points for your Healthcare Provider
5. Medical Safety & Escalation Guidance (when to contact a doctor)
    `;

    return await this._callLLMOrFallback(prompt, {
      fallbackType: 'health_summary',
      vitalsSummary,
      symptoms,
      medications,
      recentAlerts
    });
  }

  /**
   * General interactive conversation assistant
   */
  async chat({ userMessage, conversationHistory = [], healthContext = {} }) {
    const messages = [
      { role: 'system', content: this.getSystemPrompt() },
      {
        role: 'system',
        content: `Current User Health Context:\n${JSON.stringify(healthContext, null, 2)}`
      }
    ];

    conversationHistory.slice(-8).forEach((msg) => {
      messages.push({
        role: msg.role === 'user' ? 'user' : 'assistant',
        content: msg.content
      });
    });

    messages.push({ role: 'user', content: userMessage });

    try {
      if (this.client && this.apiKey && this.apiKey !== 'your_api_key_here') {
        const completion = await this.client.chat.completions.create({
          model: this.model,
          messages,
          temperature: 0.3,
          max_tokens: 800
        });

        return {
          reply: completion.choices[0].message.content,
          model: this.model,
          source: 'openai',
          disclaimer: 'This response is generated by AI for informational purposes only. Consult a doctor for medical advice.'
        };
      }
    } catch (err) {
      console.warn('[AI Service] OpenAI API call failed or quota exceeded. Using safe clinical knowledge engine fallback:', err.message);
    }

    // High quality clinical rule-based engine fallback
    return this._generateSmartClinicalChatReply(userMessage, healthContext);
  }

  /**
   * Internal execution helper with robust fallback
   */
  async _callLLMOrFallback(promptText, fallbackParams) {
    try {
      if (this.client && this.apiKey && this.apiKey !== 'your_api_key_here') {
        const response = await this.client.chat.completions.create({
          model: this.model,
          messages: [
            { role: 'system', content: this.getSystemPrompt() },
            { role: 'user', content: promptText }
          ],
          temperature: 0.3,
          max_tokens: 900
        });

        return {
          content: response.choices[0].message.content,
          model: this.model,
          source: 'openai',
          disclaimer: 'Generated by AI. Informational use only. Not a medical diagnosis.'
        };
      }
    } catch (err) {
      console.warn('[AI Service] OpenAI query failed. Utilizing local intelligent clinical engine:', err.message);
    }

    return this._generateClinicalFallbackContent(fallbackParams);
  }

  /**
   * High-accuracy clinical fallback engine when OpenAI is unavailable
   */
  _generateClinicalFallbackContent(params) {
    if (params.fallbackType === 'explain_measurement') {
      const { vitalType, value, unit } = params;
      return {
        content: `### Understanding Your ${vitalType.toUpperCase()} Reading: ${value} ${unit}

**1. Physiological Overview:**
${vitalType} is a key physiological indicator of autonomic and metabolic cardiovascular regulation. Regular monitoring helps establish your personal baseline and detect deviations over time.

**2. Standard Reference Targets:**
- Typical adult baseline: Generally maintained within standard clinical guidelines (e.g. resting heart rate 60–100 bpm, blood pressure < 120/80 mmHg, SpO2 ≥ 95%).
- Your recorded value of **${value} ${unit}** has been cross-referenced against your configured clinical threshold engine.

**3. General Health & Lifestyle Considerations:**
- **Hydration & Rest:** Ensure consistent daily fluid intake and 7–8 hours of restorative sleep.
- **Measurement Conditions:** Always record measurements after resting quietly for at least 5 minutes in a seated position.
- **Stress & Caffeine:** Be mindful that stimulants, physical exertion, or stress can temporarily influence vital readings.

**4. Questions to Discuss With Your Doctor:**
- *"Is my current reading of ${value} ${unit} appropriate for my individual baseline and medical background?"*
- *"Are there specific lifestyle or medication adjustments recommended for my trend?"*

---
*Notice: This summary was generated by the automated Health Monitoring AI Engine for educational guidance only. It does not replace a clinical consultation.*`,
        model: 'clinical-rules-engine-v2',
        source: 'clinical_engine',
        disclaimer: 'Informational analysis only. Not a medical diagnosis.'
      };
    }

    // Health summary fallback
    const vitalsCount = Object.keys(params.vitalsSummary || {}).length;
    const alertCount = (params.recentAlerts || []).length;
    const symptomCount = (params.symptoms || []).length;
    const medCount = (params.medications || []).length;

    return {
      content: `### Comprehensive Health & Vital Trends Summary

**1. Executive Health Overview:**
Over the selected monitoring timeframe, **${vitalsCount} vital categories** were tracked across your profile. You have **${medCount} active medication schedules** and **${symptomCount} logged symptoms**. A total of **${alertCount} threshold alerts** were noted for clinical review.

**2. Vital Trends & Clinical Observations:**
- **Cardiovascular & Metabolic Markers:** Monitored measurements reflect active patient tracking. Records provide actionable data for your care team.
- **Alert History:** ${alertCount > 0 ? `There are ${alertCount} alert(s) on file. Review any recurring patterns with your healthcare provider.` : 'No critical deviations currently logged.'}

**3. Medication & Symptom Alignment:**
- Logged symptoms and scheduled medications have been synchronized. Continuing regular medication logging supports therapeutic adherence.

**4. Recommended Questions for Your Doctor:**
- *"Looking at my vital trends over this period, are my target goals being met?"*
- *"Should we adjust any measurement frequencies or alert thresholds based on my recent data?"*
- *"Are my reported symptoms expected with my current regimen?"*

**5. Safety & Escalation Guidance:**
If you ever experience severe symptoms such as sudden chest discomfort, shortness of breath, sudden weakness, or confusion, please contact local emergency medical services immediately.

---
*Generated by AI Health Monitoring Assistant. Informational and monitoring tool only.*`,
      model: 'clinical-rules-engine-v2',
      source: 'clinical_engine',
      disclaimer: 'Informational analysis only. Not a medical diagnosis.'
    };
  }

  _generateSmartClinicalChatReply(userMessage, healthContext) {
    const lower = userMessage.toLowerCase();
    let reply = '';

    if (lower.includes('blood pressure') || lower.includes('bp')) {
      reply = `**Blood Pressure Information & Guidance:**\n\nBlood pressure reflects the force of blood flowing through your arteries.\n- **Systolic (top number):** Pressure when your heart beats.\n- **Diastolic (bottom number):** Pressure when your heart rests between beats.\n\nAccording to AHA guidelines, standard resting blood pressure is generally considered normal below 120/80 mmHg.\n\n**Best Practice for Measuring:**\n1. Sit comfortably with your back supported for 5 minutes before reading.\n2. Keep your feet flat on the floor and arm supported at heart level.\n3. Avoid caffeine, exercise, and smoking for 30 minutes prior.\n\n*Would you like to review your recent blood pressure trends or log a new measurement?*`;
    } else if (lower.includes('heart rate') || lower.includes('pulse')) {
      reply = `**Heart Rate / Pulse Overview:**\n\nA normal resting heart rate for adults typically ranges between **60 and 100 beats per minute (bpm)**. Well-trained athletes may have a resting heart rate closer to 40-60 bpm.\n\nFactors affecting pulse include hydration, stress, temperature, caffeine, and physical activity.\n\n*If you experience sudden rapid palpitations, dizziness, or lightheadedness, make sure to sit down and rest, and inform your doctor.*`;
    } else if (lower.includes('glucose') || lower.includes('sugar') || lower.includes('diabetes')) {
      reply = `**Blood Glucose Guidance:**\n\nBlood glucose measurements indicate the concentration of glucose in your bloodstream:\n- **Fasting Normal:** 70–99 mg/dL\n- **Pre-diabetes Range (Fasting):** 100–125 mg/dL\n- **Post-Meal Target (2 hours after eating):** Typically under 140 mg/dL for non-diabetics.\n\nConsistent meal timing, balanced complex carbohydrates, and regular physical activity help support healthy glycemic control.`;
    } else if (lower.includes('doctor') || lower.includes('questions') || lower.includes('appointment')) {
      reply = `**Questions to Bring to Your Doctor Consultation:**\n\n1. *"Are my recent vital trends within the target ranges for my age and health history?"*\n2. *"Should I adjust the timing or dosage of any of my current medications?"*\n3. *"What lifestyle or dietary adjustments would best support my cardiovascular and metabolic wellness?"*\n4. *"How frequently should I record my key vitals at home?"*`;
    } else {
      reply = `Hello! I am your AI Health Assistant. I can help explain your recorded vitals (heart rate, blood pressure, blood glucose, oxygen saturation, temperature), summarize your trends over time, and help you prepare questions for your healthcare appointments.\n\n**Example things you can ask me:**\n- *"What does my blood pressure reading mean?"*\n- *"Explain normal heart rate ranges."*\n- *"What questions should I ask my doctor about my symptoms?"*\n- *"How do I prepare for my upcoming consultation?"*\n\n*Please remember that I am an informational tool and cannot diagnose medical conditions or change prescriptions.*`;
    }

    return {
      reply,
      model: 'clinical-assistant-local',
      source: 'clinical_engine',
      disclaimer: 'Informational analysis only. Not a substitute for professional medical care.'
    };
  }
}

module.exports = new AIService();
